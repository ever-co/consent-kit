/**
 * Public type surface for consent-gate.
 */

/** The four categories every consuming site must map its trackers onto. */
export const CONSENT_CATEGORIES = ['necessary', 'analytics', 'marketing', 'preferences'] as const;

export type ConsentCategory = (typeof CONSENT_CATEGORIES)[number];

/** Every category except `necessary` — i.e. everything that requires an opt-in. */
export type GatedCategory = Exclude<ConsentCategory, 'necessary'>;

export const GATED_CATEGORIES: readonly GatedCategory[] = ['analytics', 'marketing', 'preferences'];

/**
 * A tracker declaration.
 *
 * This is the ONLY way to get a third-party script onto the page through this
 * library. There is deliberately no "render this script tag for me" helper and
 * no way to hand the caller back a `<script>` element: the library owns
 * injection, so a declared tracker physically cannot fire before its category
 * is granted.
 */
export interface TrackerDefinition {
  /** Stable, unique id. Used for de-duplication and `hasLoaded(id)`. */
  id: string;

  /** Category the tracker belongs to. Anything but `necessary` needs an opt-in. */
  category: ConsentCategory;

  /** Human label, shown in nothing — purely for debugging / audit output. */
  label?: string;

  /** External script URL. Mutually usable with `code` and `onGrant`. */
  src?: string;

  /** Inline script body. */
  code?: string;

  /** Extra attributes to set on the injected `<script>` (e.g. data-*, nonce). */
  attributes?: Record<string, string>;

  /** `<script async>`. Defaults to `true` for `src` trackers. */
  async?: boolean;

  /** `<script defer>`. */
  defer?: boolean;

  /** `type` attribute. Defaults to `text/javascript`. */
  type?: string;

  /** Where to append the script. Defaults to `head`. */
  appendTo?: 'head' | 'body';

  /**
   * Arbitrary side effect to run once the category is granted — use this for
   * SDKs that are already bundled into your app (`posthog.init(...)`,
   * `mixpanel.init(...)`). Runs at the same moment the script would be injected,
   * never before.
   */
  onGrant?: (context: TrackerGrantContext) => void | Promise<void>;

  /**
   * Cleanup hook, run when a previously granted category is withdrawn.
   * Runs before the injected node is removed and before any reload.
   */
  onRevoke?: () => void;

  /**
   * Cookie names (string or RegExp) this tracker writes, erased on withdrawal.
   */
  cookies?: Array<string | RegExp>;
}

export interface TrackerGrantContext {
  tracker: TrackerDefinition;
  record: ConsentRecord | null;
}

/**
 * The stored, auditable proof of what the user chose.
 * Derived from the CMP's own first-party cookie — we do not write a second one.
 */
export interface ConsentRecord {
  /** Opaque per-browser id generated by the CMP (uuid v4). */
  id: string;
  /** Numeric CMP revision — bump it to re-ask everyone. */
  revision: number;
  /** Your own policy version string, echoed back for audit purposes. */
  policyVersion?: string;
  /** Categories the user granted, always including `necessary`. */
  categories: ConsentCategory[];
  /** ISO timestamp of the first consent action. */
  grantedAt: string;
  /** ISO timestamp of the most recent update. */
  updatedAt: string;
  /** Language the notice was shown in. */
  languageCode?: string;
}

export type ConsentChangeListener = (record: ConsentRecord | null, granted: ConsentCategory[]) => void;

/**
 * Legacy DOM events to re-emit when consent is granted.
 *
 * Migration safety: `iubenda_consent_given` is re-emitted by default because at
 * least one existing site gates its analytics on a hand-rolled listener for that
 * exact event. Dropping Iubenda must not silently drop working consent gating.
 */
export interface LegacyEventOptions {
  /** Event names to dispatch. Default: `['iubenda_consent_given']`. */
  names?: string[];
  /**
   * Dispatch only when at least one of these categories is granted.
   * Default: `['analytics', 'marketing']` — i.e. never on a reject-all.
   */
  categories?: GatedCategory[];
}

export interface CategoryCopy {
  title: string;
  description: string;
}

export interface ConsentCopy {
  bannerTitle?: string;
  bannerDescription?: string;
  acceptAll?: string;
  rejectAll?: string;
  managePreferences?: string;
  preferencesTitle?: string;
  preferencesDescription?: string;
  savePreferences?: string;
  close?: string;
  privacyPolicyHref?: string;
  privacyPolicyLabel?: string;
  categories?: Partial<Record<ConsentCategory, CategoryCopy>>;
}

export interface ConsentCookieOptions {
  name?: string;
  domain?: string;
  path?: string;
  sameSite?: 'Strict' | 'Lax' | 'None';
  expiresAfterDays?: number;
}

export interface ConsentOptions {
  /** Everything you want gated. Declared up front; injected only after consent. */
  trackers?: TrackerDefinition[];

  /** Your privacy-policy version, stored in the consent record. */
  policyVersion?: string;

  /** CMP revision. Increment to invalidate previous consent and re-ask. */
  revision?: number;

  /** Show the notice automatically when there is no valid consent. Default `true`. */
  autoShow?: boolean;

  /** Cookie storage tuning. */
  cookie?: ConsentCookieOptions;

  /**
   * Reload the page when a previously granted category is withdrawn.
   * Default `true` — a third-party script cannot truly be unloaded, so a reload
   * is the only honest way to stop it. Set `false` in tests/SPAs that handle
   * teardown themselves via `onRevoke`.
   */
  reloadOnRevoke?: boolean;

  /** Legacy event bridge. `false` disables it. Default: Iubenda bridge on. */
  legacyEvents?: false | LegacyEventOptions;

  /** Language code shown by default. Default `'en'`. */
  language?: string;

  /** Override the built-in English copy. */
  copy?: ConsentCopy;

  /** Element the modals get appended to. Default `document.body`. */
  root?: string | Element | null;

  /** Called on every consent change, including the initial restore on load. */
  onChange?: ConsentChangeListener;

  /**
   * Escape hatch for extra CookieConsent v3 config. Compliance-critical keys
   * (`mode`, `disablePageInteraction`, `categories`, `manageScriptTags`,
   * `equalWeightButtons`) are validated and will throw if set unsafely.
   */
  cmp?: Record<string, unknown>;

  /** Swap the UI. Used by the in-memory test adapter; defaults to CookieConsent v3. */
  ui?: ConsentUiAdapter;
}

/** Contract between the gating engine and whatever renders the notice. */
export interface ConsentUiAdapter {
  mount(context: ConsentUiContext): Promise<void>;
  showBanner(): void;
  showPreferences(): void;
  setCategories(categories: ConsentCategory[]): void;
  reset(eraseCookie?: boolean): void;
  eraseCookies?(cookies: Array<string | RegExp>): void;
  destroy?(): void;
}

export interface ConsentUiContext {
  options: ConsentOptions;
  /** Categories the UI must offer, `necessary` first and always read-only. */
  categories: readonly ConsentCategory[];
  /**
   * The UI calls this whenever the user's choice changes (and once on restore).
   * `record` may be null before any choice has been made.
   */
  onConsent(granted: ConsentCategory[], record: ConsentRecord | null): void;
}

export interface ConsentInstance {
  /** Resolves once the UI is mounted and any stored consent has been applied. */
  readonly ready: Promise<void>;
  isGranted(category: ConsentCategory): boolean;
  grantedCategories(): ConsentCategory[];
  hasLoaded(trackerId: string): boolean;
  getRecord(): ConsentRecord | null;
  /** Register a tracker after init. Injects immediately IF already consented. */
  registerTracker(tracker: TrackerDefinition): void;
  accept(categories: ConsentCategory[] | 'all' | 'necessary'): void;
  acceptAll(): void;
  rejectAll(): void;
  showBanner(): void;
  /** The persistent preference-centre entry point. */
  showPreferences(): void;
  /** Wipe the stored record and re-ask. Withdrawal must be as easy as granting. */
  reset(): void;
  onChange(listener: ConsentChangeListener): () => void;
  destroy(): void;
}
